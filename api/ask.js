    '- 勞動檢查員現有7人，另以身心障礙者就業基金增置2名助理員協助行政庶務。115年3月本縣公司及商業登記37,901家，約占全國2%；中央補助地方勞檢員額全國325名。每年執行檢查及法遵訪視至少1,300件；中央如調整員額，本府將積極爭取。',
